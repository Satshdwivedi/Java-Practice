public class ladderifexample {
    public static void main(String[] args) {
        int m = 95;
        if (m > 90) {
            System.out.println("Grade A");
        } else if (m > 80 && m < 90) {
            System.out.println("Grade B");
        } else if (m > 70 && m < 80) {
            System.out.println("Grade C");
        } else {
            System.out.println("Fail");
        }
    }
}
